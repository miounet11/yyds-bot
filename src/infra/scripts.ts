import type { Brief } from "../brief/types.js";

export function dnsPlan(brief: Brief): { apply: boolean; reason: string; records: { type: string; name: string; content: string; proxied: boolean }[] } {
  const records = [
    { type: "A", name: brief.domain.canonical_host, content: brief.server.ssh_host, proxied: brief.cloudflare.proxied },
    ...brief.domain.aliases.map((alias) => ({
      type: "CNAME",
      name: alias.host,
      content: brief.domain.canonical_host,
      proxied: brief.cloudflare.proxied
    }))
  ];
  const apply = brief.mode === "production" && brief.cloudflare.enabled;
  return {
    apply,
    reason: apply ? "Apply when CLOUDFLARE_API_TOKEN and CLOUDFLARE_ZONE_ID are set." : "Plan only. Local mode or Cloudflare disabled does not call the API.",
    records
  };
}

export async function applyDns(
  zoneId: string,
  token: string,
  records: { type: string; name: string; content: string; proxied: boolean }[],
  fetchImpl: typeof fetch = fetch
): Promise<string[]> {
  const notes: string[] = [];
  for (const record of records) {
    const response = await fetchImpl(`https://api.cloudflare.com/client/v4/zones/${zoneId}/dns_records`, {
      method: "POST",
      headers: { authorization: `Bearer ${token}`, "content-type": "application/json" },
      body: JSON.stringify(record)
    });
    notes.push(`${record.name} HTTP ${response.status}`);
  }
  return notes;
}

export function nginxConf(brief: Brief): string {
  const root = `${brief.server.web_root}/current`;
  const canonical = brief.domain.canonical_host;
  const redirects = brief.domain.aliases.filter((alias) => alias.action === "redirect_301");
  const aliases = brief.domain.aliases.filter((alias) => alias.action === "canonical_only");
  return `# generated by yyds-bot
server {
  listen 80;
  listen [::]:80;
  server_name ${canonical};
  root ${root};
  index index.html;
  location / {
    if ($http_accept ~* "text/markdown") {
      rewrite ^/$ /index.md last;
      rewrite ^(.+)/$ $1/index.md last;
    }
    try_files $uri $uri/index.html $uri.html =404;
    add_header Link '</llms.txt>; rel="describedby"' always;
  }
}
${redirects
  .map(
    (alias) => `server {
  listen 80;
  server_name ${alias.host};
  return 301 ${brief.domain.scheme}://${canonical}$request_uri;
}`
  )
  .join("\n")}
${aliases
  .map(
    (alias) => `# canonical_only ${alias.host} serves the same files and HTML canonical points at ${canonical}
server {
  listen 80;
  server_name ${alias.host};
  root ${root};
  index index.html;
  location / { try_files $uri $uri/index.html =404; }
}`
  )
  .join("\n")}
`;
}

export function bootstrapScript(brief: Brief): string {
  const skipCert = /\.(example|invalid|test|localhost)$/.test(brief.domain.canonical_host);
  return `#!/usr/bin/env bash
# Idempotent host bootstrap generated by yyds-bot. Re-running is safe.
set -euo pipefail
if [[ "\${YYDS_BOOTSTRAP_EXECUTE:-}" != "1" ]]; then
  echo "Refusing to change this machine. Re-run with YYDS_BOOTSTRAP_EXECUTE=1 after review."
  exit 2
fi
if command -v apt-get >/dev/null 2>&1; then
  sudo apt-get update
  sudo apt-get install -y nginx certbot python3-certbot-nginx
fi
sudo mkdir -p ${brief.server.web_root}/releases ${brief.server.web_root}/current
sudo cp "$(dirname "$0")/nginx.conf" /etc/nginx/sites-available/${brief.project.id}.conf
sudo ln -sfn /etc/nginx/sites-available/${brief.project.id}.conf /etc/nginx/sites-enabled/${brief.project.id}.conf
sudo nginx -t
sudo systemctl enable nginx
sudo systemctl reload nginx
${
  skipCert
    ? `echo "Skipping certbot for documentation host ${brief.domain.canonical_host}."`
    : `sudo certbot --nginx -d ${brief.domain.canonical_host} ${brief.domain.aliases.map((alias) => `-d ${alias.host}`).join(" ")} --non-interactive --agree-tos -m ${brief.brand.contact.email.value ?? "admin@localhost"} || true`
}
sudo cp "$(dirname "$0")/yyds-autopilot.service" /etc/systemd/system/yyds-autopilot.service
sudo cp "$(dirname "$0")/yyds-autopilot.timer" /etc/systemd/system/yyds-autopilot.timer
sudo systemctl daemon-reload
sudo systemctl enable --now yyds-autopilot.timer
echo "bootstrap complete"
`;
}

export function autopilotUnits(brief: Brief): { service: string; timer: string; shell: string } {
  return {
    service: `[Unit]
Description=yyds-bot content, reindex, and measurement loop for ${brief.project.id}
[Service]
Type=oneshot
ExecStart=${brief.server.web_root}/infra/autopilot.sh
`,
    timer: `[Unit]
Description=Daily yyds-bot autopilot for ${brief.project.id}
[Timer]
OnCalendar=daily
Persistent=true
[Install]
WantedBy=timers.target
`,
    shell: `#!/usr/bin/env bash
set -euo pipefail
if [[ -z "\${YYDS_BIN:-}" ]]; then
  echo "YYDS_BIN is unset. Install yyds-bot and point YYDS_BIN at the yyds executable."
  exit 0
fi
exec "$YYDS_BIN" autopilot --brief ${brief.server.web_root}/brief.expanded.yaml
`
  };
}
